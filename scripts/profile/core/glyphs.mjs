// Draws glyph `name` with its top-left corner at (x, y), scaled to `size` px.
export function glyph(name, { x = 0, y = 0, size = 16, stroke = '#a1a1a1', strokeWidth = 1.75, opacity } = {}) {
  const shapes = G[name]
  if (!shapes) throw new Error(`unknown glyph "${name}"`)
  const s = size / 24
  const parts = shapes.map((shape) => {
    if (typeof shape === 'string') return h('path', { d: shape })
    if (shape.c) return h('circle', { cx: shape.c[0], cy: shape.c[1], r: shape.c[2] })
    const [rx, ry, w, hh, r] = shape.r
    return h('rect', { x: rx, y: ry, width: w, height: hh, rx: r })
  })
  return h(
    'g',
    {
      transform: `translate(${x} ${y}) scale(${Math.round(s * 1000) / 1000})`,
      stroke,
      'stroke-width': strokeWidth / s,
      'stroke-linecap': 'round',
      'stroke-linejoin': 'round',
      fill: 'none',
      opacity,
    },
    parts,
  )
}
